"""
Generates components/ket/icons.jinja (icon / stars / shape / smile / logo macros) from the
prototype's ICON, STAR and BRAND data in ../ket-product.html, so both stay identical.

usage: python3 ket/make_icons.py      (run from src/zid-theme)
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
s = open(os.path.join(HERE, '..', '..', 'ket-product.html')).read()
B = json.loads(re.search(r'const BRAND = (\{.*?\});\n', s, re.S).group(1))
icons = dict(re.findall(r"\s*(\w+): '([^']*)'", re.search(r'const ICON = \{(.*?)\n\};', s, re.S).group(1)))
star = re.search(r"const STAR = '([^']*)'", s).group(1)
star_svg = '<svg width="{{ size }}" height="{{ size }}" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true">' + star + '</svg>'

out = ['{# KET icons, stars and brand shapes — generated by ket/make_icons.py from ket-product.html #}',
       '{% set KET_ICONS = ' + json.dumps(icons) + ' %}',
       '''{% macro icon(name, size=22, sw=1.5) -%}
<svg width="{{ size }}" height="{{ size }}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="{{ sw }}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{{ KET_ICONS[name] | safe }}</svg>
{%- endmacro %}''',
       '{% macro stars(rating, size=15, label=\'\') -%}\n{% set r = (rating or 0) | float %}\n'
       '<span class="stars" role="img" aria-label="{{ label or r }}">{% for i in range(5) %}{% set f = [[r - i, 0] | max, 1] | min %}'
       '<span class="star">' + star_svg + '<span class="star__fill" style="width:{{ (f * 100) | round(0) | int }}%">' + star_svg + '</span></span>{% endfor %}</span>\n{%- endmacro %}']
for n, v in B['SHAPES'].items():
    out.append(f'{{% set KET_SHAPE_{n.upper()} %}}<svg class="shape" viewBox="0 0 {v["w"]} {v["h"]}" aria-hidden="true"><path fill="{v["c"]}" fill-rule="evenodd" d="{v["d"]}"/></svg>{{% endset %}}')
out.append('{% macro shape(name) -%}{{ {"lav": KET_SHAPE_LAV, "green": KET_SHAPE_GREEN, "blue": KET_SHAPE_BLUE}[name] }}{%- endmacro %}')
out.append('{% set KET_SHAPE_TINT = ' + json.dumps({n: v['c'] for n, v in B['SHAPES'].items()}) + ' %}')
sm, K = B['SMILE'], B['KET']
out.append(f'{{% macro smile(w=40) -%}}<svg viewBox="0 0 {sm["w"]} {sm["h"]}" width="{{{{ w }}}}" aria-hidden="true" fill="currentColor"><path d="{sm["d"]}"/></svg>{{%- endmacro %}}')
out.append(f'{{% macro logo(w=64) -%}}<svg class="klogo" viewBox="0 0 {K["w"]} {K["h"]}" width="{{{{ w }}}}" role="img" aria-label="ket" style="direction:ltr" fill="currentColor"><g class="klogo__word"><path class="kl" d="{K["k"]}"/><path class="kl" fill-rule="evenodd" d="{K["e"]}"/><path class="kl" d="{K["t"]}"/></g><g transform="translate({K["smile"]["x"]} {K["smile"]["y"]})"><path class="klogo__smile" d="{K["smile"]["d"]}"/></g></svg>{{%- endmacro %}}')
# grey product silhouettes for related products without a photo (chosen by name in product.jinja)
ph = dict(re.findall(r"\s*(\w+): '([^']*)'", re.search(r'const PH = \{(.*?)\n\};', s, re.S).group(1)))
out.append('{% set KET_PH = ' + json.dumps(ph) + ' %}')
out.append('{% macro ph(shape) -%}<svg class="ph" viewBox="0 0 160 160" aria-hidden="true"><g fill="#DCDCDC">{{ KET_PH[shape] | safe }}</g></svg>{%- endmacro %}')
dst = os.path.join(HERE, '..', 'components', 'ket', 'icons.jinja')
open(dst, 'w').write('\n'.join(out) + '\n')
print('wrote', dst, sorted(icons))
