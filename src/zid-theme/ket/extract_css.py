"""
Copies the prototype's CSS (../ket-product.html, the design source of truth) into the theme as
assets/ket.css, scoped under .ket so it cannot clash with the Growth theme's Tailwind styles.

  :root / body        -> .ket                      (the design tokens and base text styles)
  html[lang="ar"] .x  -> html[lang="ar"] :where(.ket) .x
  .x                  -> :where(.ket) .x
  :where() adds no specificity, so every rule keeps the weight it has in the prototype (otherwise
  the base rules for a / button / img would beat the 3D hero's own classes).
  @keyframes / @font-face are left alone; @media / @supports are scoped inside.
Then ket/overrides.css (theme-only fixes) is appended.

usage: python3 ket/extract_css.py      (run from src/zid-theme)
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', '..', 'ket-product.html')
OUT = os.path.join(HERE, '..', 'assets', 'ket.css')
DROP = ('#ket-hero{ margin-top', '#ket-hero .kh-canvas{ top')   # page-only hacks for the prototype header

html = open(SRC).read()
# the page's main stylesheet: the first <style> block that defines the design tokens
blocks = re.findall(r'<style>(.*?)</style>', html, re.S)
css = next(b for b in blocks if ':root{' in b and '--f-latin' in b)
css = '\n'.join(l for l in css.split('\n') if not l.strip().startswith(DROP))

def scope_sel(sel):
    sel = sel.strip()
    if not sel or sel.startswith(('from', 'to')) or re.fullmatch(r'[\d.]+%(\s*,\s*[\d.]+%)*', sel):
        return sel
    m = re.match(r'^(html(?:\[[^\]]*\]|\.[\w-]+|:not\([^)]*\))*|:root)(.*)$', sel)   # html, html[lang], html.x, html:not(.x)
    if m:
        root, rest = m.group(1), m.group(2).strip()
        if root == ':root':
            return '.ket' + (' ' + rest if rest else '')
        return f'{root} :where(.ket)' + (' ' + rest if rest else '') if rest else f'{root} .ket'
    if sel.startswith('body'):
        return '.ket' + sel[4:]
    return ':where(.ket) ' + sel

def scope_block(text):
    out, i, n = [], 0, len(text)
    while i < n:
        j = text.find('{', i)
        if j < 0:
            out.append(text[i:]); break
        head = text[i:j]
        # find the matching close brace
        depth, k = 1, j + 1
        while k < n and depth:
            if text[k] == '{': depth += 1
            elif text[k] == '}': depth -= 1
            k += 1
        body = text[j + 1:k - 1]
        h = head.strip()
        lead = head[:len(head) - len(head.lstrip())]
        if h.startswith(('@media', '@supports', '@layer')):
            out.append(f'{lead}{h}{{{scope_block(body)}}}')
        elif h.startswith(('@keyframes', '@font-face', '@property')):
            out.append(f'{lead}{h}{{{body}}}')
        else:
            # keep comments before the selector
            cm = re.match(r'^((?:\s*/\*.*?\*/)*)(.*)$', h, re.S)
            pre, sels = cm.group(1), cm.group(2)
            parts = [scope_sel(s) for s in re.split(r',(?![^(]*\))', sels)]
            out.append(f'{lead}{pre}{", ".join(parts)}{{{body}}}')
        i = k
    return ''.join(out)

scoped = scope_block(css)
extra = open(os.path.join(HERE, 'overrides.css')).read() if os.path.exists(os.path.join(HERE, 'overrides.css')) else ''
open(OUT, 'w').write('/* KET design system — generated by ket/extract_css.py from ket-product.html. Edit the prototype\n   or ket/overrides.css, not this file. */\n' + scoped + '\n/* ---- theme overrides (ket/overrides.css) ---- */\n' + extra)
print('wrote', OUT, len(scoped) + len(extra), 'bytes')
