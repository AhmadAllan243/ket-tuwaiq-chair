"""
Builds assets/ket-trees.css: the trees department's own look (loader, planting banner, strip, initiative page,
yellow and light green), taken from the approved design ../ket-trees.html (made by ../make_trees.py) and scoped
under .kc--trees, so it only touches the trees department. Run after ../make_trees.py; ket/build_category.py
adds the markup (components/ket/trees-*.jinja) and the loader.

usage: python3 ket/build_trees.py      (run from src/zid-theme)
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kscope

HERE = os.path.dirname(os.path.abspath(__file__))
THEME = os.path.join(HERE, '..')
html = open(os.path.join(THEME, '..', 'ket-trees.html')).read()
a = html.index('/* ===================== TREES: watering loader')
b = html.index('/* ===================== ANNOUNCEMENT + HEADER', a)
css = html[a:b]
css = css.replace('#heroCard > #heroImg', '.hero__card > #heroImg').replace('.hero #heroCard', '.hero .hero__card')

head = """/* KET trees department — generated by ket/build_trees.py from ket-trees.html. Edit the design, not this file. */
/* yellow most of the way, the light green as a touch */
.kc.kc--trees{ --lime:#C4F5A4; --pink:#F8FA75; --blush:#F8FA75; --rose:#F8FA75; --pink-l:#FCFDD9; --yellow:#F8FA75; --yellow-l:#FCFDD9; --yellow-d:#E6E85A; }
:where(.kc--trees) .hero__pink, :where(.kc--trees) .hero__stat svg, :where(.kc--trees) .srow__plus{ color:var(--forest); }
:where(.kc--trees) .hero > .hero__h{ display:none; }   /* the photo opens the page; the words are in the planting banner */
:where(.kc--trees) .hero__media{ margin-top:clamp(36px, 4vw, 56px); }
"""
out = head + kscope.make('.kc--trees')(css, 'kt')
open(os.path.join(THEME, 'assets', 'ket-trees.css'), 'w').write(out)
print('built ket-trees.css', len(out))
