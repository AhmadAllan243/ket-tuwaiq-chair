"""
Builds the lighting department (category 444478) from its approved design ../ket-lamps.html (made by ../make_lamps.py):

  assets/ket-lamps.css                  the design's CSS scoped under .kl
  assets/ket-lamps.js                   the design's script on Zid data (the department's products)
  components/ket/lamps-page.jinja       the markup + the data the script reads (window.KET_LAMPS)
  assets/ket-lamps/*.webp               the photos (banner, rooms, the lamps' lit pictures)

templates/category.jinja shows lamps-page.jinja for the lighting department and the usual category page for the
others (the switch is in ket/ket-category.data.jinja). Each lamp gets its type, family and lit picture from the design
by its store slug; a lamp added later still shows (no lit picture, the last type) until the design is rebuilt.
The rooms in "touch the light" are not store products, so they offer "shop lighting" in place of a price.

usage: python3 ket/build_lamps.py      (run from src/zid-theme, after ../make_lamps.py)
"""
import os, re, json, subprocess, sys, shutil
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import kscope
from PIL import Image

THEME = os.path.join(HERE, '..')
SRC = os.path.join(THEME, '..')
html = open(os.path.join(SRC, 'ket-lamps.html')).read()

def must(s, a, b, n=1):
    c = s.count(a)
    assert c == n, f'expected {n}x, found {c}: {a[:90]}'
    return s.replace(a, b)

def cut(s, start, end, repl=''):
    i = s.index(start); j = s.index(end, i) + len(end)
    return s[:i] + repl + s[j:]

# ---------------------------------------------------------------- CSS
css = re.findall(r'<style>(.*?)</style>', html, re.S)[0]
css = cut(css, '/* ===================== ANNOUNCEMENT + HEADER', '/* ===================== 1. HERO', '/* ===================== 1. HERO')
css = cut(css, '/* ===================== FOOTER', '.toast{', '.toast{')
css = '\n'.join(l for l in css.split('\n') if not l.startswith(('.skip', '.wa{', '.wa ', '.wa:')))
extra = """
/* ---- theme-only ---- */
.kl{ position:relative; }
.kl > section{ isolation:isolate; }
html:not(.is-loading) :where(.kl) .loader:not(.is-out){ display:none; }   /* return visits: no loader (one fading out stays until its fade ends) */
:where(.kl) .klogo .kl{ transform-box:fill-box; transform-origin:50% 100%; }
:where(.kl) .klogo__smile{ opacity:0; }
:where(.kl) .pager{ display:flex; justify-content:center; gap:8px; margin-top:40px; }
:where(.kl) .pager a{ min-width:44px; height:44px; padding-inline:14px; display:grid; place-items:center; border-radius:999px; background:var(--white); font-weight:600; text-decoration:none; }
:where(.kl) .pager a.is-on{ background:var(--black); color:var(--white); }
"""
open(os.path.join(THEME, 'assets', 'ket-lamps.css'), 'w').write(
    '/* KET lighting department — generated by ket/build_lamps.py from ket-lamps.html. Edit the design, not this file. */\n'
    + kscope.make('.kl')(css, 'kl') + extra)

# ---------------------------------------------------------------- the design's data
store_js = re.search(r'<script>\nconst M = .*?\nconst STORE = (\{.*?\n\});\n</script>', html, re.S).group(1)
proto = json.loads(subprocess.run(['node', '-e', f'const S = {store_js}; process.stdout.write(JSON.stringify(S))'],
                                  capture_output=True, text=True, check=True).stdout)
# each lamp's type, family and lit picture, by its store slug
SLUG = {}
for p in proto['products']:
    slug = p['url'].rsplit('/products/', 1)[1]
    SLUG[slug] = [p['type'], p['col'], p['id']]

# ---------------------------------------------------------------- JS
js = re.findall(r'<script>\n(\(\(\) => \{.*?\}\)\(\);)\n</script>', html, re.S)[0]
js = must(js, "'use strict';", """'use strict';
const KL = document.querySelector('.kl'); if (!KL || !window.KET_LAMPS) return;
const D = window.KET_LAMPS, A = D.assets || {};
D.products.forEach(p => { const m = SLUGS[p.slug] || []; p.type = m[0] || 'statement'; p.col = m[1] || ''; p.on = (m[2] && A[m[2] + '-on']) || '';
  p.price = +p.price || 0; p.was = +p.was || 0; if (p.was <= p.price) p.was = 0; });
const TYPES = PTYPES.map(x => ({ ...x, hero: (D.products.find(p => p.type === x.id) || {}).id || '' })).filter(x => x.hero);
const COLS = PCOLS.map(c => ({ ...c, img: (D.products.find(p => p.col === c.id) || {}).id || '' })).filter(c => c.img);
const COLIMG = {}; COLS.forEach(c => COLIMG[c.id] = c.img);
const STORE = { currency: CURRENCY, category: { ar: D.name, en: D.name }, types: TYPES, products: D.products, collections: COLS, gallery: GALLERY, ui: UI };
if (TYPES.length < 2) document.getElementById('shape').style.display = 'none';""")
js = must(js, "root.classList.add(G ? 'motion' : 'no-motion');", "KL.classList.add(G ? 'motion' : 'no-motion');")
js = must(js, "let lang = 'ar';", "let lang = /^en/.test(root.lang) ? 'en' : 'ar';")
js = must(js, "const img = id => `${M}${id}.webp`;\nconst P = STORE.products, byId = Object.fromEntries(P.map(p => [p.id, p]));",
          "const P = STORE.products, byId = Object.fromEntries(P.map(p => [p.id, p]));\n"
          "const img = k => (byId[k] && byId[k].img) || A[k] || '';\n"
          "const lit = k => (byId[k] && (byId[k].on || byId[k].img)) || img(k);   // a lamp switched on (its own lit picture), else as it is")
js = must(js, "const minPrice = Math.min(...P.map(p => p.price)), maxOff = Math.max(...P.map(off));",
          "const minPrice = P.length ? Math.min(...P.map(p => p.price)) : 0, maxOff = Math.max(0, ...P.filter(p => p.was).map(off));")
js = '\n'.join(l for l in js.split('\n') if not l.startswith((
    "$('#searchBtn').innerHTML", "$('#accountBtn')", "$('#cartBtn')", "$('#logo').innerHTML", "$('#footerSmile')", "$('#wa')", "$('#social')",
    "const grp = ", "$('#marquee')", "  document.title = ", "  $('#langBtn')", "  $('#vatNo')", "$('#langBtn').onclick",
    "const header = $('#header');", "addEventListener('scroll', () => header", "    .from('#logo .klogo__word'")))
# shop by type: the lamps switched on; a missing type or family leaves its tile out
js = must(js, "img(ty(id).hero + '-on')", "lit(ty(id).hero)")
js = must(js, "img(im + '-on')", "lit(im)")
js = must(js, "const tile = (id, cls, tint) => `", "const tile = (id, cls, tint) => !ty(id) ? '' : `")
js = must(js, "const col = (id, cls, im, tint, label) => { const c = STORE.collections.find(x => x.id === id), ph = !!byId[im]?.photo;",
          "const col = (id, cls, im, tint, label) => { const c = STORE.collections.find(x => x.id === id), ph = !!byId[im]?.photo; if (!c) return '';")
js = must(js, "col('glass', 'st--short', 'lp18', 'white')", "col('glass', 'st--short', COLIMG.glass, 'white')")
js = must(js, "col('gold', 'st--full', 'lp17', 'white', true)", "col('gold', 'st--full', COLIMG.gold, 'white', true)")
# the cards: the store's prices, its own lit picture, the Zid cart
js = must(js, '<img class="card__on" src="${img(p.id + \'-on\')}" alt="" loading="lazy" width="640" height="640">',
          '${p.on ? `<img class="card__on" src="${p.on}" alt="" loading="lazy" width="900" height="900">` : \'\'}')
js = must(js, '<p class="card__price"><b>${money(p.price)}</b><s>${fmt(p.was)}</s></p>', '<p class="card__price"><b>${p.fprice || money(p.price)}</b>${p.was ? `<s>${p.fwas || fmt(p.was)}</s>` : \'\'}</p>')
js = must(js, '<span class="card__off" dir="ltr">−${off(p)}%</span>', '${p.was ? `<span class="card__off" dir="ltr">−${off(p)}%</span>` : \'\'}')
js = cut(js, "$('#pgrid').addEventListener('click', e => {", "\n});\n", """$('#pgrid').addEventListener('click', async e => {
  const b = e.target.closest('[data-add]'); if (!b) return; e.preventDefault();
  const p = byId[b.dataset.add]; if (p.hasOptions || !window.zid) { location.href = p.url; return; }
  try { await zid.cart.addProduct({ product_id: p.id, quantity: 1 }, { showErrorNotification: true });
    window.dispatchEvent(new CustomEvent('cart:updated', { detail: { productId: p.id, action: 'add' } })); toast(t('added', { n: L(p) })); }
  catch (err) { location.href = p.url; }
});
""")
# touch the light: the rooms are not store products, so "shop lighting" in place of a price and add to cart
js = must(js, "    <p class=\"card__price gx__price\"><b>${money(g.price)}</b><s>${fmt(g.was)}</s></p>\n", "")
js = must(js, "<button class=\"gx__add\" type=\"button\" data-gx-add>${icon('bag', 18, 1.8)}<span>${t('add')}</span></button>",
          "<a class=\"gx__add\" href=\"#all\" data-gx-shop><span>${t('galBtn')}</span>${icon('arrow', 18, 2)}</a>")
js = must(js, "  if (e.target.closest('[data-gx-add]')) {", "  if (e.target.closest('[data-gx-shop]')) { e.preventDefault(); goGrid(); return; }\n  if (e.target.closest('[data-gx-add]')) {")
# the banner pins under the store's own header
js = must(js, "$('#header').offsetHeight", "(document.getElementById('ket-top') || { offsetHeight: 0 }).offsetHeight")
# the loader: the department's own lamps in the ring
js = re.sub(r"const pick = \[\[.*?\]\];", "const pick = P.slice(0, 8).map((p, i) => [p.id, ['circle', 'arch', 'sq', 'pill'][i % 4], ['#D4C5FF', '#F4F4F4', '#F8FA75', '#F0EBFF'][i % 4]]);", js, count=1, flags=re.S)
js = must(js, "    .addLabel('out', '-=.55')\n", "    .addLabel('out', '-=.55')\n    .add(() => ldr.classList.add('is-out'), 'out')\n")
open(os.path.join(THEME, 'assets', 'ket-lamps.js'), 'w').write(
    '/* KET lighting department — generated by ket/build_lamps.py from ket-lamps.html. Edit the design, not this file. */\n'
    f'const UI = {json.dumps(proto["ui"], ensure_ascii=False)};\nconst CURRENCY = {json.dumps(proto["currency"], ensure_ascii=False)};\n'
    f'const PTYPES = {json.dumps(proto["types"], ensure_ascii=False)};\nconst PCOLS = {json.dumps(proto["collections"], ensure_ascii=False)};\n'
    f'const GALLERY = {json.dumps(proto["gallery"], ensure_ascii=False)};\nconst SLUGS = {json.dumps(SLUG, ensure_ascii=False)};\n' + js + '\n')

# ---------------------------------------------------------------- the photos
OUT = os.path.join(THEME, 'assets', 'ket-lamps'); os.makedirs(OUT, exist_ok=True)
loader = html[html.index('<!-- LOADER'):html.index('<div class="announce"')]
main = html[html.index('<main id="main">') + len('<main id="main">'):html.index('</main>')]
tail = html[html.index('<div class="toast"'):html.index('</dialog>') + len('</dialog>')]
names = set(re.findall(r'media/lamps/([\w-]+)\.webp', loader + main + tail))
for g in proto['gallery']: names |= {g['id'] + '-off', g['id'] + '-on', g['id'] + '-cut'}
names |= set(re.findall(r"img\('([\w-]+)'\)", js))                      # pictures the script names (the grid's photo tile)
names |= {p[2] + '-on' for p in SLUG.values()}                           # every lamp's lit picture
names = sorted(n for n in names if os.path.exists(os.path.join(SRC, 'media', 'lamps', n + '.webp')))
for n in names:
    im = Image.open(os.path.join(SRC, 'media', 'lamps', n + '.webp'))
    if max(im.size) > 1400: im.thumbnail((1400, 1400))
    im.save(os.path.join(OUT, n + '.webp'), quality=80, method=6)

# ---------------------------------------------------------------- markup
def asset(m): return "{{ 'ket-lamps/" + m.group(1) + ".webp' | asset_url }}"
loader = re.sub(r'media/lamps/([\w-]+)\.webp', asset, loader)
main = re.sub(r'media/lamps/([\w-]+)\.webp', asset, main)
main = must(main, '<div class="pgrid" id="pgrid"></div>', '<div class="pgrid" id="pgrid"></div>\n  {% include "components/ket/category-pager.jinja" %}')
main = must(main, '<a class="btn btn-wa" href="#" data-toast="soon">', '<a class="btn btn-wa" href="{{ KL_WA }}" target="_blank" rel="noopener">')
assert 'media/' not in main + loader + tail, re.findall(r'media/[^"]*', main + loader + tail)
data = """{#
  KET lighting department (design: ket-lamps.html). Generated by ket/build_lamps.py: edit the design or this block in
  the script, then run the build. Shown by templates/category.jinja for category 444478.
#}
{% set R = products.results if products and products.results else [] %}
{% macro href(v) %}{{ ((v._url if v and v._url else (v.url if v and v.url is string else (v or ''))) ~ '') | tojson }}{% endmacro %}
{% macro pimg(p, w=900) -%}
  {%- set im = p.main_image.image.large if p.main_image and p.main_image.image else (p.images[0].image.full_size if p.images else '') -%}
  {{- image_url(im, w=w, q=85, f='auto') if im else '' -}}
{%- endmacro %}
{% set phone = (store.settings.contact.phone or '') | replace('+', '') | replace(' ', '') %}
{% set KL_WA = ('https://wa.me/' ~ phone) if phone else '#' %}
<link rel="stylesheet" href="{{ 'ket-lamps.css' | asset_url }}">
<script>
  try { if (!sessionStorage.getItem('ketLampsSeen') && !/[?&]page=/.test(location.search)) document.documentElement.classList.add('is-loading'); } catch (e) {}   // the ring loader: first visit of a session only
  window.KET_LAMPS = {
    name: {{ category.name | tojson }},
    assets: {
      """ + ',\n      '.join("%s: {{ ('ket-lamps/%s.webp' | asset_url) | tojson }}" % (json.dumps(n), n) for n in names) + """
    },
    products: [
      {% for p in R %}
        { id: {{ (p.id | string) | tojson }}, slug: {{ (p.slug or '') | tojson }}, ar: {{ p.name | tojson }}, en: {{ p.name | tojson }},
          url: {{ href(url_for('product_details', slug=p.slug)) }}, img: {{ pimg(p) | tojson }},
          price: {{ (p.sale_price if p.sale_price else p.price) | tojson }}, was: {{ (p.price if p.sale_price else 0) | tojson }},
          fprice: {{ (p.formatted_sale_price or p.formatted_price or '') | tojson }}, fwas: {{ (p.formatted_price if p.formatted_sale_price else '') | tojson }},
          hasOptions: {{ (p.has_options or false) | tojson }} }{{ ',' if not loop.last }}
      {% endfor %}
    ]
  };
</script>
"""
open(os.path.join(THEME, 'components', 'ket', 'lamps-page.jinja'), 'w').write(data + '<div class="kl">\n' + loader + main + tail + '\n</div>\n' + """
<script src="https://cdnjs.cloudflare.com/ajax/libs/gsap/3.12.5/gsap.min.js"></script>
<script src="https://cdnjs.cloudflare.com/ajax/libs/gsap/3.12.5/ScrollTrigger.min.js"></script>
<script src="https://cdn.jsdelivr.net/npm/lenis@1.1.13/dist/lenis.min.js"></script>
<script src="{{ 'ket-brand.js' | asset_url }}"></script>
<script src="{{ 'ket-lamps.js' | asset_url }}"></script>
""")
print('built lamps: js', len(js), 'photos', len(names))
